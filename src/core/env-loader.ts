import crypto from 'node:crypto';
import fs from 'node:fs';
import type { EncryptedEnvVault } from './types.js';

export function parseDotEnv(
  content: string,
  baseEnv: Record<string, string | undefined> = process.env
): Record<string, string> {
  const result: Record<string, string> = {};
  const lines = content.split(/\r?\n/);

  for (const rawLine of lines) {
    const trimmed = rawLine.trim();
    if (!trimmed || trimmed.startsWith('#') || trimmed.startsWith(';')) {
      continue;
    }

    const match = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_.-]*)\s*=\s*(.*)$/.exec(trimmed);
    if (!match) continue;

    const key = match[1]!;
    let rawVal = match[2] ?? '';

    if (
      (rawVal.startsWith('"') && rawVal.endsWith('"')) ||
      (rawVal.startsWith("'") && rawVal.endsWith("'"))
    ) {
      const quote = rawVal[0]!;
      rawVal = rawVal.slice(1, -1);
      if (quote === '"') {
        rawVal = rawVal.replace(/\\n/g, '\n').replace(/\\"/g, '"');
      }
    } else {
      const commentIdx = rawVal.indexOf(' #');
      if (commentIdx !== -1) {
        rawVal = rawVal.slice(0, commentIdx).trim();
      }
    }

    // Expand ${VAR} or $VAR using already-parsed values or baseEnv
    const expanded = rawVal.replace(
      /\$\{([A-Za-z_][A-Za-z0-9_]*)\}|\$([A-Za-z_][A-Za-z0-9_]*)/g,
      (_m, braced?: string, plain?: string) => {
        const varName = (braced ?? plain)!;
        return result[varName] ?? baseEnv[varName] ?? '';
      }
    );

    result[key] = expanded;
  }

  return result;
}

export function formatDotEnv(vars: Record<string, string>): string {
  const lines = [
    '# Generated by mcp-shield migrate',
    '# Do NOT commit this file to version control (.gitignore)'
  ];
  for (const [k, v] of Object.entries(vars)) {
    const needsQuotes = /[\s#"']/.test(v);
    const escaped = needsQuotes ? `"${v.replace(/"/g, '\\"')}"` : v;
    lines.push(`${k}=${escaped}`);
  }
  return lines.join('\n') + '\n';
}

export function encryptEnvVault(
  vars: Record<string, string>,
  passphrase: string
): EncryptedEnvVault {
  const kdfSalt = crypto.randomBytes(16);
  const key = crypto.scryptSync(passphrase, kdfSalt, 32);
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);

  const plaintext = Buffer.from(JSON.stringify(vars), 'utf8');
  const ciphertext = Buffer.concat([cipher.update(plaintext), cipher.final()]);
  const authTag = cipher.getAuthTag();

  return {
    version: 1,
    encrypted: true,
    createdAt: new Date().toISOString(),
    kdf: 'scrypt',
    kdfSaltHex: kdfSalt.toString('hex'),
    ivHex: iv.toString('hex'),
    authTagHex: authTag.toString('hex'),
    ciphertextHex: ciphertext.toString('hex')
  };
}

export function decryptEnvVault(
  vault: EncryptedEnvVault,
  passphrase: string
): Record<string, string> {
  if (!vault || vault.version !== 1 || !vault.encrypted) {
    throw new Error('Invalid mcp-shield encrypted vault format.');
  }

  const kdfSalt = Buffer.from(vault.kdfSaltHex, 'hex');
  const iv = Buffer.from(vault.ivHex, 'hex');
  const authTag = Buffer.from(vault.authTagHex, 'hex');
  const ciphertext = Buffer.from(vault.ciphertextHex, 'hex');

  const key = crypto.scryptSync(passphrase, kdfSalt, 32);
  const decipher = crypto.createDecipheriv('aes-256-gcm', key, iv);
  decipher.setAuthTag(authTag);

  try {
    const decrypted = Buffer.concat([decipher.update(ciphertext), decipher.final()]);
    return JSON.parse(decrypted.toString('utf8')) as Record<string, string>;
  } catch {
    throw new Error('Failed to decrypt .mcp-vault.json: invalid passphrase or tampered file.');
  }
}

export function loadSecretsFromSources(options: {
  envFiles?: string[];
  vaultFile?: string;
  passphrase?: string;
  baseEnv?: Record<string, string | undefined>;
}): Record<string, string> {
  const combined: Record<string, string> = {};
  const base = options.baseEnv ?? process.env;

  for (const [k, v] of Object.entries(base)) {
    if (typeof v === 'string') {
      combined[k] = v;
    }
  }

  if (options.envFiles) {
    for (const file of options.envFiles) {
      const content = fs.readFileSync(file, 'utf8');
      const parsed = parseDotEnv(content, combined);
      Object.assign(combined, parsed);
    }
  }

  if (options.vaultFile) {
    const raw = fs.readFileSync(options.vaultFile, 'utf8');
    const vault = JSON.parse(raw) as EncryptedEnvVault;
    const pass = options.passphrase ?? combined.MCP_SHIELD_PASSPHRASE;
    if (!pass) {
      throw new Error(
        'Encrypted vault requires --passphrase or MCP_SHIELD_PASSPHRASE environment variable.'
      );
    }
    const decrypted = decryptEnvVault(vault, pass);
    Object.assign(combined, decrypted);
  }

  return combined;
}
